// Generates tokens.css from the Screens v2 design-system bundle: every :root / [data-theme] block that declares
// design tokens (not Tailwind internals), with its @media context kept. Then appends loop-theme.css verbatim.
// Usage: node tools/extract-tokens.mjs > tokens.css   (test/loop-ui.test.mjs checks the committed file is current)
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(pkg, "source", "_ds_bundle.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const theme = readFileSync(join(pkg, "source", "loop-theme.css"), "utf8");

/** Parse into nested { prelude, body | children } nodes. */
function parse(s) {
  const out = []; let i = 0;
  function block(level) {
    const nodes = [];
    while (i < s.length) {
      const open = s.indexOf("{", i), close = s.indexOf("}", i);
      if (close !== -1 && (open === -1 || close < open)) { i = close + 1; return nodes; }
      if (open === -1) { i = s.length; return nodes; }
      const prelude = s.slice(i, open).trim().split(";").pop().trim(); i = open + 1;
      if (prelude.startsWith("@")) nodes.push({ prelude, children: block(level + 1) });
      else { const end = s.indexOf("}", i); nodes.push({ prelude, body: s.slice(i, end) }); i = end + 1; }
    }
    return nodes;
  }
  out.push(...block(0));
  return out;
}
const isTokenSel = (p) => /(^|,)\s*(:root|:host|\[data-theme(="(light|dark)")?\])\s*(,|$)/.test(p) && !/[ >+~]/.test(p.replace(/\s*,\s*/g, ","));
function emit(nodes, media) {
  const lines = [];
  for (const n of nodes) {
    if (n.children) {
      const m = n.prelude.startsWith("@media") ? n.prelude : null;
      if (n.prelude.startsWith("@layer") || n.prelude.startsWith("@supports") && false || m) lines.push(...emit(n.children, m || media));
      continue;
    }
    if (!isTokenSel(n.prelude)) continue;
    const decls = n.body.split(";").map((d) => d.trim()).filter((d) => /^--[\w-]+\s*:/.test(d) && !d.startsWith("--tw"));
    if (!decls.length) continue;
    const rule = `${n.prelude} {\n${decls.map((d) => `  ${d.replace(/\s*:\s*/, ": ")};`).join("\n")}\n}`;
    lines.push(media ? `${media} {\n${rule.replace(/^/gm, "  ")}\n}` : rule);
  }
  return lines;
}
const body = emit(parse(src)).join("\n");
process.stdout.write(`/* @loop/ui tokens — GENERATED by tools/extract-tokens.mjs. Do not edit.
   Source: Screens v2 design artifact a74ae02c, ds/rc/_ds_bundle.css (tokens only) + ds/rc/loop-theme.css (verbatim). */
${body}
/* ---- loop-theme.css (verbatim) ---- */
${theme.trim()}
`);
